"""
NETGUARD - Page 6: Security Analysis Engine
Detailed view of all algorithmic findings generated by the security rule engine,
evidence strings, step-by-step solutions, and verification methodologies.
"""

import textwrap
import streamlit as st
from database import get_latest_scan, award_xp
from config import CYBER_PALETTE


def render_security_page():
    """Renders the comprehensive security analysis findings."""
    active_scan = st.session_state.get("active_scan")
    if not active_scan:
        active_scan = get_latest_scan()
        if active_scan:
            st.session_state["active_scan"] = active_scan

    if not active_scan:
        st.info("No audit active. Please run a scan from the Network Scanner page first.")
        return

    findings = active_scan.get("findings", [])
    scan_id = active_scan.get("scan_id", "N/A")

    if findings:
        award_xp("THREATS_REVIEWED", scan_id, 40, f"Reviewed {len(findings)} security vulnerability findings")

    st.html(textwrap.dedent("""
    <div class="netguard-card" style="margin-bottom: 20px;">
        <div style="display: flex; justify-content: space-between; align-items: center; flex-wrap: wrap; gap: 10px;">
            <div>
                <div style="font-size: 0.78rem; font-weight: 700; color: #00D9FF; letter-spacing: 0.08em; text-transform: uppercase;">
                    MISSION 03: THREAT SURFACE SWEEP
                </div>
                <h2 style="color: #F3F7FF; font-size: 1.55rem; font-weight: 800; margin: 2px 0 0 0;">
                    Threat Surface Analysis Center
                </h2>
                <p style="color: #91A3B8; font-size: 0.88rem; margin-top: 4px; margin-bottom: 0;">
                    Deterministic vulnerability evaluations derived from open port banners and protocol exposures.
                    Each threat includes technical risk explanations and tactical verification steps.
                </p>
            </div>
            <div>
                <span class="badge-commander">Threat Surface Core</span>
            </div>
        </div>
    </div>
    """))

    if not findings:
        st.success("🎉 Zero security exposures identified. All evaluated endpoints adhere to clean security standards.")
        return

    # Filter Controls
    c_f1, c_f2 = st.columns([1, 1])
    with c_f1:
        sev_filter = st.selectbox(
            "Filter by Severity",
            options=["All Severities", "Critical", "High", "Medium", "Low"]
        )
    with c_f2:
        device_ips = list({f.get("device_ip") for f in findings})
        dev_filter = st.selectbox(
            "Filter by Affected Host",
            options=["All Hosts"] + device_ips
        )

    filtered_findings = []
    for f in findings:
        if sev_filter != "All Severities" and f.get("severity") != sev_filter:
            continue
        if dev_filter != "All Hosts" and f.get("device_ip") != dev_filter:
            continue
        filtered_findings.append(f)

    st.markdown(f"**Identified {len(filtered_findings)} security findings**")
    st.html("<div style='margin-bottom: 16px;'></div>")

    for f in filtered_findings:
        f_id = f.get("id", "FIND-000")
        title = f.get("title", "Security Finding")
        ip = f.get("device_ip", "Unknown")
        hostname = f.get("hostname", "Unknown Host")
        port = f.get("port", "N/A")
        sev = f.get("severity", "Low")
        evidence = f.get("evidence", "No raw evidence captured.")
        explanation = f.get("explanation", "")
        solution = f.get("solution", "")
        verification = f.get("verification", "")
        manual_check = f.get("requires_manual_verification", False)

        if sev == "Critical":
            sev_badge = '<span class="badge-critical">CRITICAL SEVERITY</span>'
            border_color = CYBER_PALETTE["critical"]
        elif sev == "High":
            sev_badge = '<span class="badge-high">HIGH SEVERITY</span>'
            border_color = CYBER_PALETTE["warning"]
        elif sev == "Medium":
            sev_badge = '<span class="badge-medium">MEDIUM SEVERITY</span>'
            border_color = "#F59E0B"
        else:
            sev_badge = '<span class="badge-low">LOW SEVERITY</span>'
            border_color = CYBER_PALETTE["cyan"]

        manual_tag = '<span style="color: #FFB020; font-size: 0.75rem; background: rgba(255, 176, 32, 0.12); padding: 2px 7px; border-radius: 4px; font-weight:600;">Manual Check Recommended</span>' if manual_check else '<span style="color: #00F5A0; font-size: 0.75rem; background: rgba(0, 245, 160, 0.12); padding: 2px 7px; border-radius: 4px; font-weight:600;">Port Evidence Confirmed</span>'

        st.html(textwrap.dedent(f"""
        <div style="background: #111C2E; border: 1px solid #1E2D4A; border-left: 4px solid {border_color}; border-radius: 10px; padding: 18px 22px; margin-bottom: 14px;">
            <div style="display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 8px;">
                <div>
                    <span style="font-size: 0.78rem; color: #00D9FF; font-family: monospace; font-weight: 700;">{f_id}</span>
                    <h3 style="color: #F3F7FF; font-size: 1.25rem; font-weight: 800; margin: 2px 0 4px 0;">{title}</h3>
                    <span style="font-size: 0.85rem; color: #91A3B8;">
                        Target: <b style="color: #00D9FF;">{ip}</b> ({hostname}) &nbsp;|&nbsp; Port: <b style="color: #FFFFFF;">{port}/tcp</b>
                    </span>
                </div>
                <div style="text-align: right;">
                    {sev_badge}<br/>
                    <div style="margin-top: 5px;">{manual_tag}</div>
                </div>
            </div>

            <div style="background: #070B14; border: 1px solid #1E2D4A; border-radius: 6px; padding: 10px 14px; margin: 10px 0; font-family: 'JetBrains Mono', monospace; font-size: 0.82rem; color: #00F5A0;">
                <b>Detected Evidence:</b> {evidence}
            </div>

            <div style="margin: 12px 0;">
                <p style="color: #CBD5E1; font-size: 0.9rem; line-height: 1.5; margin-bottom: 10px;">
                    <b style="color: #F3F7FF;">Why This Matters:</b> {explanation}
                </p>
                <div style="background: rgba(0, 217, 255, 0.05); border-left: 3px solid #00D9FF; padding: 10px 14px; border-radius: 4px; margin-bottom: 8px;">
                    <b style="color: #00D9FF; font-size: 0.85rem;">Remediation Guidance:</b>
                    <div style="color: #E2E8F0; font-size: 0.85rem; line-height: 1.5; white-space: pre-line; margin-top: 4px;">{solution}</div>
                </div>
                <div style="color: #91A3B8; font-size: 0.82rem;">
                    <b>Verification Check:</b> <span style="font-family: monospace; color: #00F5A0;">{verification}</span>
                </div>
            </div>
        </div>
        """))

        col_act1, col_act2 = st.columns([1, 4])
        with col_act1:
            if st.button("💬 Consult AI Core", key=f"ai_btn_{f_id}", use_container_width=True):
                st.session_state["selected_finding_for_ai"] = f
                st.session_state["current_page"] = "AI Security Assistant"
                st.rerun()
